package com.swipesort.app

import java.util.Locale

/** Keyword ranking, not a neural vision model. Works with Cyrillic OCR output. */
internal fun detectCategory(text: String): String? {
    val t = text.lowercase(Locale.ROOT).replace('ё', 'е')
    if (t.length < 12) return null
    val keywords = linkedMapOf(
        "Чеки и платежи" to listOf("кассовый чек", "фискальн", "к оплате", "оплата прошла", "оплачено", "списание", "перевод выполнен", "возврат средств", "квитанция", "сумма платежа"),
        "Путешествия" to listOf("бронирован", "отель", "гостиниц", "авиабилет", "вылет", "посадочный", "турист", "курорт", "аэропорт", "заезд", "выезд", "номер для проживания", "booking", "hotel", "flight"),
        "Рецепты" to listOf("ингредиент", "способ приготовления", "приготовление", "разогрейте духовку", "выпекать", "добавьте муку", "порций", "тесто", "рецепт", "сковород", "запека"),
        "Здоровье" to listOf("анализ крови", "ферритин", "гемоглобин", "медицинск", "врач", "симптом", "диагноз", "обследование", "узи", "клиника", "пациент", "лечение", "дозировка"),
        "Работа и учёба" to listOf("домашнее задание", "present simple", "present continuous", "упражнение", "учебник", "школа", "английский язык", "урок", "задание", "контрольная работа", "вариант", "exercise", "grammar", "worksheet"),
        "Дети и игры" to listOf("детский сад", "детей", "ребенок", "игрушк", "занятия для детей", "развивающ", "раскраск", "мультфильм", "поделк", "настольная игра"),
        "Красота и стиль" to listOf("размер одежды", "обувь", "косметик", "парфюм", "макияж", "платье", "брюки", "стрижка", "аромат", "крем для лица"),
        "Дом" to listOf("интерьер", "ремонт", "мебель", "кухня", "планировка", "дизайн комнаты", "уборка", "посудомой", "бытовая техника"),
        "Покупки" to listOf("в корзину", "оформить заказ", "доставка", "wildberries", "ozon", "в наличии", "оформление заказа", "купить", "продавец", "товар", "артикул", "добавить в корзину"),
        "Цены и скидки" to listOf("скидка", "распродажа", "купон", "промокод", "акция", "-50%", "sale", "cashback", "кешбэк"),
        "Переписки" to listOf("whatsapp", "telegram", "сообщение", "напишите сообщение", "ответить", "пересланное", "сообщения", "чат"),
        "Документы" to listOf("паспорт", "договор", "свидетельство", "заявление", "справка", "подпись", "реквизиты", "инн", "снилс"),
        "Полезные советы" to listOf("инструкция", "как сделать", "пошагово", "лайфхак", "рекомендации", "советы", "памятка", "шаг 1"),
        "Мемы" to listOf("мем", "прикол", "смешно", "юмор", "шутка", "анекдот")
    )
    var winner: String? = null
    var winnerPoints = 0
    for ((category, patterns) in keywords) {
        val hits = patterns.count { t.contains(it) }
        if (hits > winnerPoints) {
            winnerPoints = hits
            winner = category
        }
    }
    // An explicit, distinctive phrase is enough; otherwise require two textual hints.
    val stronglyIdentifying = listOf("кассовый чек", "ингредиент", "посадочный", "бронирован",
        "домашнее задание", "present simple", "оформить заказ", "whatsapp", "telegram", "фискальн")
    return if (winnerPoints >= 2 || (winnerPoints >= 1 && stronglyIdentifying.any { t.contains(it) })) winner else null
}
